def run_loocv_shap_guided(X, y, groups, top_n=10):
    """Select top-N features by XGB importance inside each fold — no leakage."""
    all_true, all_pred, all_prob, accs, f1s = [], [], [], [], []

    for train_idx, test_idx in logo.split(X, y, groups):
        X_tr = X.iloc[train_idx].values
        X_te = X.iloc[test_idx].values
        y_tr = y.iloc[train_idx].values
        y_te = y.iloc[test_idx].values

        scaler = StandardScaler()
        X_tr = scaler.fit_transform(X_tr)
        X_te = scaler.transform(X_te)

        # Step 1: fit a quick XGB on training fold to get feature importances
        selector_model = XGBClassifier(n_estimators=50, max_depth=2,
                                       eval_metric='logloss', random_state=42)
        selector_model.fit(X_tr, y_tr)
        importances = selector_model.feature_importances_
        top_idx = np.argsort(importances)[::-1][:top_n]

        # Step 2: select those features
        X_tr_sel = X_tr[:, top_idx]
        X_te_sel = X_te[:, top_idx]

        # Step 3: SMOTE
        n_min = min(y_tr.sum(), (y_tr==0).sum())
        if n_min >= 2:
            try:
                sm = SMOTE(random_state=42, k_neighbors=min(2, n_min-1))
                X_tr_sel, y_tr = sm.fit_resample(X_tr_sel, y_tr)
            except: pass

        # Step 4: final model
        model = XGBClassifier(n_estimators=100, max_depth=3,
                              eval_metric='logloss', random_state=42)
        model.fit(X_tr_sel, y_tr)
        y_pred = model.predict(X_te_sel)
        y_prob = model.predict_proba(X_te_sel)[:, 1]

        all_true.extend(y_te); all_pred.extend(y_pred); all_prob.extend(y_prob)
        accs.append(accuracy_score(y_te, y_pred))
        f1s.append(f1_score(y_te, y_pred, zero_division=0))

