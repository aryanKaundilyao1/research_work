logo = LeaveOneGroupOut()

def run_loocv(model, X, y, groups, use_smote=True):
    """Run Leave-One-Student-Out CV, return per-fold results."""
    aucs, accs, f1s, all_true, all_pred, all_prob = [], [], [], [], [], []

    for train_idx, test_idx in logo.split(X, y, groups):
        X_tr, X_te = X.iloc[train_idx].values, X.iloc[test_idx].values
        y_tr, y_te = y.iloc[train_idx].values, y.iloc[test_idx].values

        # Scale features
        scaler = StandardScaler()
        X_tr = scaler.fit_transform(X_tr)
        X_te = scaler.transform(X_te)

        # SMOTE only if enough minority samples in training fold
        if use_smote:
            n_minority = min(y_tr.sum(), (y_tr==0).sum())
            if n_minority >= 2:
                k = min(2, n_minority - 1)
                sm = SMOTE(random_state=42, k_neighbors=k)
                try:
                    X_tr, y_tr = sm.fit_resample(X_tr, y_tr)
                except:
                    pass  # skip SMOTE if it fails for this fold

        model.fit(X_tr, y_tr)

        y_pred = model.predict(X_te)
        y_prob = model.predict_proba(X_te)[:, 1]

        all_true.extend(y_te)
        all_pred.extend(y_pred)
        all_prob.extend(y_prob)
        accs.append(accuracy_score(y_te, y_pred))
        f1s.append(f1_score(y_te, y_pred, zero_division=0))

    # Compute AUC over all folds combined
    try:
        auc = roc_auc_score(all_true, all_prob)
    except:
        auc = 0.0

    return {
        "AUC":      round(auc, 3),
        "Accuracy": round(np.mean(accs), 3),
        "F1":       round(np.mean(f1s), 3),
        "all_true": all_true,
        "all_pred": all_pred,
        "all_prob": all_prob
    }

