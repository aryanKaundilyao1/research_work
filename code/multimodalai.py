from scipy.ndimage import gaussian_filter1d

def preprocess_signal(signal_array, fs):
    s = pd.Series(signal_array).interpolate(method='linear').fillna(method='bfill').fillna(method='ffill').values.astype(float)
    std = np.std(s)
    if std > 0:
        s = (s - np.mean(s)) / std
    # Gaussian smooth — 3 minute window in samples
    sigma = max(1, int(180 * fs / 6))
    s = gaussian_filter1d(s, sigma=sigma)
    return s

# Sampling rates (Hz) for each signal
