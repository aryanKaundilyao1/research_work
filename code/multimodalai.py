def split_phases(signal_array):
    n = len(signal_array)
    b = int(0.25 * n)
    e = int(0.75 * n)
    return {
        "beginning": signal_array[:b],
        "middle":    signal_array[b:e],
        "end":       signal_array[e:]
    }

