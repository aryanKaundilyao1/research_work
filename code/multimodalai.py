def extract_hrv_features(ibi_segment, prefix=""):
    try:
        rr = ibi_segment["IBI"].dropna().values * 1000  # to milliseconds
        if len(rr) < 5:
            return {}
        diff_rr = np.diff(rr)
        return {
            f"{prefix}hrv_mean_rr":   np.mean(rr),
            f"{prefix}hrv_std_rr":    np.std(rr),
            f"{prefix}hrv_rmssd":     np.sqrt(np.mean(diff_rr**2)),
            f"{prefix}hrv_pnn50":     np.sum(np.abs(diff_rr) > 50) / len(diff_rr) * 100,
            f"{prefix}hrv_median_rr": np.median(rr),
            f"{prefix}hrv_range_rr":  np.max(rr) - np.min(rr),
            f"{prefix}hrv_min_rr":    np.min(rr),
            f"{prefix}hrv_max_rr":    np.max(rr),
        }
    except:
        return {}

