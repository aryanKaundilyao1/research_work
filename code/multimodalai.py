from sklearn.feature_selection import SelectKBest, f_classif, mutual_info_classif
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

def run_loocv_with_selection(model, X, y, groups, k=50, selector='anova'):
    """LOOCV with feature selection applied inside each fold (no data leakage)."""
    all_true, all_pred, all_prob = [], [], []
    accs, f1s = [], []

    scorer = f_classif if selector == 'anova' else mutual_info_classif

    for train_idx, test_idx in logo.split(X, y, groups):
        X_tr, X_te = X.iloc[train_idx].values, X.iloc[test_idx].values
        y_tr, y_te = y.iloc[train_idx].values, y.iloc[test_idx].values

        # Scale
        scaler = StandardScaler()
        X_tr = scaler.fit_transform(X_tr)
        X_te = scaler.transform(X_te)

        # Select k best features — fit on training only
        sel = SelectKBest(scorer, k=min(k, X_tr.shape[1]))
        X_tr = sel.fit_transform(X_tr, y_tr)
        X_te = sel.transform(X_te)

        # SMOTE
        n_minority = min(y_tr.sum(), (y_tr==0).sum())
        if n_minority >= 2:
            try:
                sm = SMOTE(random_state=42, k_neighbors=min(2, n_minority-1))
                X_tr, y_tr = sm.fit_resample(X_tr, y_tr)
            except:
                pass

        model.fit(X_tr, y_tr)
        y_pred = model.predict(X_te)
        y_prob = model.predict_proba(X_te)[:, 1]

        all_true.extend(y_te)
        all_pred.extend(y_pred)
        all_prob.extend(y_prob)
        accs.append(accuracy_score(y_te, y_pred))
        f1s.append(f1_score(y_te, y_pred, zero_division=0))

    try:
        auc = roc_auc_score(all_true, all_prob)
    except:
        auc = 0.0

    return {
      "AUC": round(auc, 3),
      "Accuracy": round(np.mean(accs), 3),
      "F1": round(np.mean(f1s), 3),
      "all_true": all_true,
      "all_pred": all_pred,
      "all_prob": all_prob
    }

